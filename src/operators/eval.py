"""File loads checkpoint, runs test metrics test_rel_l2, outputs test_rel_l2"""

# -------- LOAD TEST SET ---------

def build_test_loader(config):

    # not calling create_dataloaders because only test dataloader is needed
    x_data, y_data = load_numpy_data(config['data']['x_data_path'], config['data']['y_data_path'])
    _, _, _, _, in_f_test, out_f_test = split_tensors(x_data, y_data, config['data']['train_split'], config['data']['val_split'], config['data']['test_split'])

    # create test set data loader
    test_set = DataLoader(TensorDataset(in_f_test, out_f_test), batch_size=config['training']['batch_size'], shuffle=False)
    return test_set

# -------- EVAL MODEL ON TEST SET  ---------

def evaluate(model, test_loader):

    with torch.no_grad():
        model.eval()
        test_loss = 0.0

        for x_batch, y_batch in test_loader:
            y_pred = model(x_batch)

            test_rel_l2 = (torch.mean((y_pred - y_batch)**2)/torch.mean(y_batch**2))**0.5 * 100

            test_loss += test_rel_l2.item()

        # average test loss across all batches
        test_loss /= len(test_loader)

    return test_loss


# --------- EVAL ALL SEEDS IN RUNS ---------

def eval_all_seeds(run_root: str):
    run_root = Path(run_root)
    results = []

    for seed_dir in sorted(run_root.glob("seed*")):
        ckpt_path = seed_dir / "fno1d_best.pt"
        if not ckpt_path.exists():
            continue

        ckpt = torch.load(ckpt_path, map_location="cpu")
        config = ckpt['config']

        test_loader = build_test_loader(config)

        fno = FNO1d(config['model']['parameters']['modes'], config['model']['parameters']['width'])
        fno.load_state_dict(ckpt['model_state'])

        test_rel_l2 = evaluate(model=fno, test_loader=test_loader)

        results.append(
            {
                "seed": ckpt.get("seed", seed_dir.name),
                "best_epoch": ckpt["epoch"],
                "best_val": float(ckpt["best_val"]),
                "test_rel_l2": float(test_rel_l2),
                "ckpt": str(ckpt_path)
            }
        )

    # sort by test performance (done by sort() which goes from smallest -> largest)
    results.sort(key= lambda r: r['test_rel_l2'])
    return results


# ---------- COMPUTE MEAN + STD FOR TEST ERROR ACROSS SEEDS ----------

def mean_std(values: list[float]) -> tuple[float, float]:
    """Sample std for small-n reporting; returns (mean, std)."""
    n = len(values)
    if n ==0:
        return float("nan"), float("nan")
    mu = sum(values)/n
    if n==1:
        return mu, 0.0
    # variance formula for a sample
    var = sum((x-mu) ** 2 for x in values) / (n-1)
    return mu, math.sqrt(var)

def print_seed_report(results: list[dict]) -> dict:
    best_vals = [r['best_val'] for r in results]
    test_rel_l2 = [r['test_rel_l2'] for r in results]

    # compute the mean and std for both validation loss and test loss
    val_mu, val_std = mean_std(best_vals)
    test_mu, test_std = mean_std(test_rel_l2)

    # print seed report
    print("\n===== Seed Report =====")
    print(f"Number of seeds: {len(results)}")
    print(f"best_val_loss mean & standard dist. ({val_mu}, {val_std})")
    print(f"test_rel_l2 mean & standard dist. ({test_mu}, {test_std})")

    # also print best seed by lowest test error
    best = min(results, key= lambda r: r['test_rel_l2'])
    print(f"Best by lowest test error: seed={best['seed']} test_rel_l2={best['test_rel_l2']}")

    # return dict
    return {
        "num_seeds": len(results),
        "best_val_loss_mean": val_mu,
        "best_val_loss_std": val_std,
        "test_rel_l2_mean": test_mu,
        "test_rel_l2_std": test_std
    }

