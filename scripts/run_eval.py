import argparse
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Evaluate trained FNO2D checkpoints on the test split.",
    )
    parser.add_argument(
        "run_root",
        help="Path to a config directory containing seed*/ subdirs (e.g. $HOME/fno_runs/exp/config0).",
    )
    parser.add_argument(
        "--write-test-records", action="store_true",
        help="Also write per-pair CSVs and provenance beside each seed checkpoint using the same inference pass.",
    )
    parser.add_argument(
        "--records-name", default="test_records.csv",
        help="CSV filename per seed when --write-test-records is enabled (default: test_records.csv).",
    )
    parser.add_argument(
        "--no-figures", action="store_true",
        help=(
            "Skip the benchmark case figure that --write-test-records otherwise "
            "renders into run_root/figures/."
        ),
    )
    parser.add_argument(
        "--figures-dir", default=None,
        help="Where to write the case figure (default: run_root/figures).",
    )
    parser.add_argument(
        "--device", choices=("cpu", "cuda", "mps", "auto"), default=None,
        help="Override the checkpoint's evaluation device.",
    )
    parser.add_argument(
        "--data-dir",
        default=None,
        help=(
            "Optional dataset directory to evaluate against instead of the paths "
            "baked into the checkpoint. Used for cross-resolution eval: point a "
            "100x100-trained checkpoint at a finer-grid dataset (only the test "
            "split is consumed; training-distribution normalization is reused)."
        ),
    )
    parser.add_argument(
        "--report-name",
        default="seed_report.json",
        help="Filename for the saved report under run_root (e.g. seed_report_r200.json).",
    )
    parser.add_argument(
        "--padding-reference-resolution",
        type=int,
        default=None,
        help=(
            "Scale FNO padding to preserve the physical padding width from this "
            "training resolution. For a 100x100-trained checkpoint, use 100."
        ),
    )
    parser.add_argument(
        "--rollout-num-substeps",
        type=int,
        default=None,
        help=(
            "Opt into homogeneous autoregressive rollout with this many substeps. "
            "Omit to use checkpoint/config defaults; values greater than 1 enable rollout."
        ),
    )
    parser.add_argument(
        "--long-lead-only",
        action="store_true",
        help=(
            "Evaluate only full-span pairs (source t=0 -> target t_final), one per "
            "test sim — the hardest, maximum-lead prediction where autoregressive "
            "rollout is expected to help most."
        ),
    )
    parser.add_argument(
        "--eval-all-sims",
        action="store_true",
        help=(
            "Evaluate every simulation in the (redirected) dataset instead of the "
            "15%% held-out test slice. Use for OOD datasets generated by "
            "data/generate_ood_dataset.py so all OOD sims get a row."
        ),
    )
    parser.add_argument(
        "--time-norm-horizon",
        type=float,
        default=None,
        help=(
            "Trained normalization horizon (e.g. 0.30) for temporal model-input "
            "features ONLY. The physical t_final stays the dataset's true horizon, "
            "so a target past this value yields lead/time features > 1.0 (true "
            "time-OOD). Defaults to t_final (no change)."
        ),
    )
    parser.add_argument(
        "--target-times",
        default=None,
        help=(
            "Comma-separated target times for the OOD time protocols "
            "(e.g. 0.25,0.30,0.35,0.40,0.45)."
        ),
    )
    parser.add_argument(
        "--protocol",
        action="append",
        default=None,
        choices=["fixed_initial", "anchored_from_horizon", "ood_local_fixed_lead"],
        help=(
            "OOD time pair protocol(s); repeatable. fixed_initial (t_s=0, ID+OOD "
            "targets), anchored_from_horizon (t_s=horizon, OOD targets), "
            "ood_local_fixed_lead (t_s>horizon, fixed lead)."
        ),
    )
    args = parser.parse_args()

    run_root = Path(args.run_root).expanduser()
    if not run_root.is_dir():
        print(f"error: run_root does not exist or is not a directory: {run_root}", file=sys.stderr)
        return 1

    seed_dirs = sorted(run_root.glob("seed*"))
    if not seed_dirs:
        print(f"error: no seed*/ subdirectories found under {run_root}", file=sys.stderr)
        return 1

    print(f"Evaluating run_root: {run_root}")
    print(f"Found {len(seed_dirs)} seed dir(s): {[d.name for d in seed_dirs]}")

    from src.operators.eval import eval_all_seeds, print_seed_report, save_report

    rollout_enabled = None
    if args.rollout_num_substeps is not None:
        rollout_enabled = args.rollout_num_substeps > 1

    target_times = None
    if args.target_times is not None:
        target_times = [float(t) for t in args.target_times.split(",") if t.strip()]

    results = eval_all_seeds(
        str(run_root),
        data_dir=args.data_dir,
        report_name=args.report_name,
        padding_reference_resolution=args.padding_reference_resolution,
        rollout_enabled=rollout_enabled,
        rollout_num_substeps=args.rollout_num_substeps,
        long_lead_only=args.long_lead_only,
        eval_all_sims=args.eval_all_sims,
        time_norm_horizon=args.time_norm_horizon,
        target_times=target_times,
        protocols=args.protocol,
        write_records=args.write_test_records,
        records_name=args.records_name,
        device=args.device,
    )
    if not results:
        print(f"error: no fno2d_best.pt checkpoints found under {run_root}", file=sys.stderr)
        return 1

    for r in results:
        print(
            f"seed={r['seed']} best_epoch={r['best_epoch']} "
            f"best_val={r['best_val']:.6f} "
            f"test_rel_l2_norm={r['test_rel_l2_norm']:.6f} "
            f"test_rel_l2_phys={r['test_rel_l2']:.6f} "
            f"test_iface_rel_l2_norm={r['test_iface_rel_l2_norm']:.6f} "
            f"test_iface_rel_l2_phys={r['test_iface_rel_l2']:.6f} "
            f"test_boundary_rel_l2_norm={r['test_boundary_rel_l2_norm']:.6f} "
            f"test_boundary_rel_l2_phys={r['test_boundary_rel_l2']:.6f} "
            f"num_sims={r['num_sims']}"
        )

    summary = print_seed_report(results)
    save_report(run_root=str(run_root), results=results, summary=summary, report_name=args.report_name)

    if args.write_test_records and not args.no_figures:
        render_case_figure(run_root, args.records_name, args.figures_dir)
    return 0


def render_case_figure(run_root: Path, records_name: str, out_dir: str | None) -> None:
    """Draw the benchmark's case figure from the records this eval just wrote.

    Deliberately non-fatal. The evaluation's own output is already on disk by
    this point, and a plotting problem -- a stale checkpoint format, a dataset
    the figure cannot reach, no matplotlib in the environment -- is not a reason
    to fail a job whose numbers are fine.
    """
    try:
        from visual.pub.autorender import render_run
    except ImportError as exc:
        print(f"warning: skipping case figure, plotting unavailable: {exc}", file=sys.stderr)
        return
    try:
        paths = render_run(run_root, records_name=records_name, out_dir=out_dir)
    except Exception as exc:
        print(f"warning: could not render case figure: {type(exc).__name__}: {exc}",
              file=sys.stderr)
        return
    if not paths:
        print("No case figure is defined for this benchmark.")
    for path in paths:
        print(f"Saved figure -> {path}")


if __name__ == "__main__":
    raise SystemExit(main())
